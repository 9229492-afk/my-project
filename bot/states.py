"""Состояния диалога оформления заказа (FSM).

FSM — это способ помнить, на каком шаге разговора находится пользователь.
Без него пришлось бы гадать, что означает присланный текст: имя, телефон
или адрес. aiogram хранит текущий шаг для каждого пользователя отдельно.
"""

from aiogram.fsm.state import State, StatesGroup


class OrderStates(StatesGroup):
    """Шаги: имя → телефон → способ получения → адрес → подтверждение.

    Адрес спрашиваем не всегда: при самовывозе этот шаг пропускается.
    """

    name = State()
    phone = State()
    delivery = State()
    address = State()
    confirm = State()
